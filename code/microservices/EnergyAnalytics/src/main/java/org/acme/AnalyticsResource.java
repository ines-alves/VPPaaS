package org.acme;

import org.acme.model.ConsumedByProsumerAnalyticsRequest;
import org.acme.model.DischargedByZoneAnalyticsRequest;
import org.acme.model.GeneratedByProsumerAnalyticsRequest;
import org.acme.model.SoCAnalyticsRequest;
import org.eclipse.microprofile.config.inject.ConfigProperty;

import io.quarkus.runtime.StartupEvent;
import io.smallrye.mutiny.Multi;
import io.smallrye.mutiny.Uni;
import jakarta.enterprise.event.Observes;
import jakarta.inject.Inject;
import jakarta.ws.rs.GET;
import jakarta.ws.rs.POST;
import jakarta.ws.rs.Path;
import jakarta.ws.rs.core.Response;

@Path("/analytics")
public class AnalyticsResource {

    @Inject
    AnalyticsService analyticsService;

    @Inject
    io.vertx.mutiny.mysqlclient.MySQLPool client;

    @Inject
    @ConfigProperty(name = "myapp.schema.create", defaultValue = "true") 
    boolean schemaCreate;

    void config(@Observes StartupEvent ev) {
        if (schemaCreate) {
            initdb();
        }
    }
    
    private void initdb() {
        String createAnalyticsSql = "CREATE TABLE IF NOT EXISTS analytics_record (" +
            "id SERIAL PRIMARY KEY, " +
            "metric_name VARCHAR(255) NOT NULL, " +
            "metric_value DOUBLE, " +
            "zone_id VARCHAR(255), " +
            "prosumer_id VARCHAR(255), " +
            "timestamp DATETIME)";
            
        client.query(createAnalyticsSql).execute()
            .await().indefinitely();
    }

    @POST
    @Path("/soc")
    public Uni<Response> calculateSoC(SoCAnalyticsRequest request) {
        if (request == null || request.telemetry == null || request.telemetry.isEmpty()) {
            return Uni.createFrom().item(Response.status(Response.Status.BAD_REQUEST).build());
        }

        return analyticsService.calculateSoCAnalytics(request)
            .onItem().transform(v -> Response.accepted()
                .entity(java.util.Map.of("message", "SoC analytics processed"))
                .build())
            .onFailure().recoverWithItem(e -> Response.serverError()
                .entity(java.util.Map.of("error", e.getMessage()))
                .build());
    }

    @POST
    @Path("/discharged")
    public Uni<Response> calculateDischarged(DischargedByZoneAnalyticsRequest request) {
        if (request == null || request.telemetry == null || request.telemetry.isEmpty()) {
            return Uni.createFrom().item(Response.status(Response.Status.BAD_REQUEST).build());
        }

        return analyticsService.calculateDischargedByZone(request)
            .onItem().transform(v -> Response.accepted()
                .entity(java.util.Map.of("message", "Discharged by zone analytics processed"))
                .build())
            .onFailure().recoverWithItem(e -> Response.serverError()
                .entity(java.util.Map.of("error", e.getMessage()))
                .build());
    }

    @POST
    @Path("/consumed")
    public Uni<Response> calculateConsumed(ConsumedByProsumerAnalyticsRequest request) {
        if (request == null || request.telemetry == null || request.telemetry.isEmpty() || request.prosumerId == null) {
            return Uni.createFrom().item(Response.status(Response.Status.BAD_REQUEST).build());
        }

        return analyticsService.calculateConsumedByProsumer(request)
            .onItem().transform(v -> Response.accepted()
                .entity(java.util.Map.of("message", "Consumed by prosumer analytics processed"))
                .build())
            .onFailure().recoverWithItem(e -> Response.serverError()
                .entity(java.util.Map.of("error", e.getMessage()))
                .build());
    }

    @POST
    @Path("/generated")
    public Uni<Response> calculateGenerated(GeneratedByProsumerAnalyticsRequest request) {
        if (request == null || request.telemetry == null || request.telemetry.isEmpty() || request.prosumerId == null) {
            return Uni.createFrom().item(Response.status(Response.Status.BAD_REQUEST).build());
        }

        return analyticsService.calculateGeneratedByProsumer(request)
            .onItem().transform(v -> Response.accepted()
                .entity(java.util.Map.of("message", "Generated by prosumer analytics processed"))
                .build())
            .onFailure().recoverWithItem(e -> Response.serverError()
                .entity(java.util.Map.of("error", e.getMessage()))
                .build());
    }

    @GET
    public Multi<AnalyticsRecord> getAllAnalytics() {
        return analyticsService.getAllAnalytics();
    }
}