package org.acme;

import static io.restassured.RestAssured.given;
import static org.hamcrest.Matchers.equalTo;
import static org.mockito.ArgumentMatchers.any;

import org.acme.model.ConsumedByProsumerAnalyticsRequest;
import org.acme.model.DischargedByZoneAnalyticsRequest;
import org.acme.model.GeneratedByProsumerAnalyticsRequest;
import org.acme.model.SoCAnalyticsRequest;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import io.quarkus.test.InjectMock;
import io.quarkus.test.junit.QuarkusTest;
import io.restassured.http.ContentType;
import io.smallrye.mutiny.Multi;
import io.smallrye.mutiny.Uni;
import io.vertx.mutiny.mysqlclient.MySQLPool;

@QuarkusTest
public class AnalyticsResourceTest {

    @InjectMock
    MySQLPool mysqlPool;

    @InjectMock
    AnalyticsService analyticsService;

    @Test
    public void testSoCEndpointReturnsAccepted() {
        Mockito.when(analyticsService.calculateSoCAnalytics(any(SoCAnalyticsRequest.class)))
            .thenReturn(Uni.createFrom().voidItem());

        given()
            .contentType(ContentType.JSON)
            .body("{\"telemetry\": [{\"asset_type\": \"BATTERY\", \"asset_id\": \"BATT-1\", \"grid_cell_id\": \"ZONE-1\", \"payload\": {\"soc_percent\": 80.0}}]}")
            .when().post("/analytics/soc")
            .then()
            .statusCode(202)
            .body("message", equalTo("SoC analytics processed"));
    }

    @Test
    public void testSoCEndpointReturnsBadRequestWhenTelemetryIsEmpty() {
        given()
            .contentType(ContentType.JSON)
            .body("{\"telemetry\": []}")
            .when().post("/analytics/soc")
            .then()
            .statusCode(400);
    }

    @Test
    public void testDischargedEndpointReturnsAccepted() {
        Mockito.when(analyticsService.calculateDischargedByZone(any(DischargedByZoneAnalyticsRequest.class)))
            .thenReturn(Uni.createFrom().voidItem());

        given()
            .contentType(ContentType.JSON)
            .body("{\"telemetry\": [{\"asset_type\": \"BATTERY\", \"asset_id\": \"BATT-1\", \"grid_cell_id\": \"ZONE-1\", \"payload\": {\"soc_percent\": 50.0, \"energy_available_kwh\": 5.0}}]}")
            .when().post("/analytics/discharged")
            .then()
            .statusCode(202)
            .body("message", equalTo("Discharged by zone analytics processed"));
    }

    @Test
    public void testDischargedEndpointReturnsBadRequestWhenTelemetryIsEmpty() {
        given()
            .contentType(ContentType.JSON)
            .body("{\"telemetry\": []}")
            .when().post("/analytics/discharged")
            .then()
            .statusCode(400);
    }

    @Test
    public void testConsumedEndpointReturnsAccepted() {
        Mockito.when(analyticsService.calculateConsumedByProsumer(any(ConsumedByProsumerAnalyticsRequest.class)))
            .thenReturn(Uni.createFrom().voidItem());

        given()
            .contentType(ContentType.JSON)
            .body("{\"prosumerId\": 1, \"telemetry\": [{\"asset_type\": \"EV_CHARGER\", \"asset_id\": \"EV-1\", \"grid_cell_id\": \"ZONE-1\", \"payload\": {\"session_energy_kwh\": 5.0}}]}")
            .when().post("/analytics/consumed")
            .then()
            .statusCode(202)
            .body("message", equalTo("Consumed by prosumer analytics processed"));
    }

    @Test
    public void testConsumedEndpointReturnsBadRequestWhenProsumerIdIsNull() {
        given()
            .contentType(ContentType.JSON)
            .body("{\"prosumerId\": null, \"telemetry\": [{\"asset_type\": \"EV_CHARGER\", \"asset_id\": \"EV-1\", \"grid_cell_id\": \"ZONE-1\", \"payload\": {\"session_energy_kwh\": 5.0}}]}")
            .when().post("/analytics/consumed")
            .then()
            .statusCode(400);
    }

    @Test
    public void testGeneratedEndpointReturnsAccepted() {
        Mockito.when(analyticsService.calculateGeneratedByProsumer(any(GeneratedByProsumerAnalyticsRequest.class)))
            .thenReturn(Uni.createFrom().voidItem());

        given()
            .contentType(ContentType.JSON)
            .body("{\"prosumerId\": 1, \"telemetry\": [{\"asset_type\": \"SOLAR\", \"asset_id\": \"SOL-1\", \"grid_cell_id\": \"ZONE-1\", \"payload\": {\"generation_kw\": 10.0, \"daily_yield_kwh\": 15.0}}]}")
            .when().post("/analytics/generated")
            .then()
            .statusCode(202)
            .body("message", equalTo("Generated by prosumer analytics processed"));
    }

    @Test
    public void testGeneratedEndpointReturnsBadRequestWhenProsumerIdIsNull() {
        given()
            .contentType(ContentType.JSON)
            .body("{\"prosumerId\": null, \"telemetry\": [{\"asset_type\": \"SOLAR\", \"asset_id\": \"SOL-1\", \"grid_cell_id\": \"ZONE-1\", \"payload\": {\"daily_yield_kwh\": 15.0}}]}")
            .when().post("/analytics/generated")
            .then()
            .statusCode(400);
    }

    @Test
    public void testGetAllAnalyticsReturnsList() {
        AnalyticsRecord record = new AnalyticsRecord();
        record.metricName = "Average-SoC";
        record.metricValue = 75.5;
        Mockito.when(analyticsService.getAllAnalytics())
            .thenReturn(Multi.createFrom().items(record));

        given()
            .when().get("/analytics")
            .then()
            .statusCode(200)
            .contentType(ContentType.JSON);
    }
}
